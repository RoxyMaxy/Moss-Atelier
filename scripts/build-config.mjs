// scripts/build-config.mjs
// Writes public configuration to js/config.js.
// Strictly guards against writing sensitive credentials (API keys, DB credentials).

import { writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const targetFile = resolve(rootDir, 'js/config.js');

const publicConfig = {
  SENTRY_DSN: process.env.SENTRY_DSN || '',
  HOSTED_API_URL: process.env.HOSTED_API_URL || '',
  DEFAULT_MODE: process.env.DEFAULT_MODE || 'OFFLINE',
  SEARCH_COUNTRY: process.env.SEARCH_COUNTRY || 'fr',
  SEARCH_LANG: process.env.SEARCH_LANG || 'fr'
};

// Security check: ensure no leaked tokens
const stringified = JSON.stringify(publicConfig, null, 2);
const forbiddenKeys = ['GEMINI_API_KEY', 'SERPAPI_KEY', 'DATABASE_URL', 'ELEVENLABS_API_KEY', 'BROWSERBASE_API_KEY'];

for (const key of forbiddenKeys) {
  if (process.env[key] && stringified.includes(process.env[key])) {
    console.error(`FATAL: Attempted to expose secret ${key} in client config!`);
    process.exit(1);
  }
}

const fileContent = `// Generated by scripts/build-config.mjs - DO NOT COMMIT\nexport const config = ${stringified};\n`;
writeFileSync(targetFile, fileContent, 'utf-8');
console.log('✓ js/config.js successfully generated with public keys only.');
